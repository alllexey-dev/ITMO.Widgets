    backend) slug=alllexey-dev/itmo-widgets-backend letter=B default=dev main="$PROJ/itmo-widgets-backend" ;;
    myitmoapi) slug=alllexey-dev/my-itmo-api letter=M default=master main="$PROJ/MyItmoApi" ;;
