#!/bin/bash
# integrate list <repo>
# integrate merge <repo> <pr> [--local-verify <log>]
# integrate revert <repo> <sha> <reason>
# integrate batch <repo> [--window 14|19] [--apk <file> | --build-apk]
# integrate ready [--dry-run] [--lanes <dir>]
#   common options: --pr-json <file> (PR data from a file instead of `gh pr list/view`;
#   tests and offline runs; close and comment still call gh), --board <file>
#
# ITMO.Widgets v2.3 (L01 G-13a). The integrator's merge tool. It works only in the
# integrator worktree ~/proj/.wt/<repo>/next (marker `integrator`, `lane next <repo>`)
# and pushes only refs/heads/v2.3/next there; protected refs move through `promote`.
#
#   repo  android | backend | myitmoapi | web (core has no v2.3/next; L01-CF PRs into
#         core master, like PRs into release/*, go to promote)
#
# list    open PRs into v2.3/next: item IDs from the title, head CI, changed paths vs the
#         body's `Surface:` globs, size (changed lines, renames aside; > 1500 flagged),
#         master section 6 hot files touched, queue length (section 4.5 stop above 10).
# merge   base v2.3/next only; head v2.3/<lane>/<slug> (title `<ID>[, <ID>]: <summary>`)
#         or, in android only, dependabot/* by dependabot (surface = build files,
#         refused while an L04 PR touching build files is open, commit
#         `TC-08: <title> (#<n>)`); CI green on the head (no check runs: --local-verify
#         <log> ending `VERIFY <R> <mode> PASS ... <head sha7>` plus a PASS `Verify:` line
#         in the body); every changed path inside `Surface:` unless a PR comment starts
#         with "surface OK". Squash onto fresh origin/v2.3/next, commit `<title> (#<n>)`,
#         push, close the PR with "Squash-merged into v2.3/next as <sha>", board rows of
#         the title's IDs -> merged. A conflict aborts, comments "rebase on v2.3/next"
#         and leaves the PR open.
# revert  `git revert --no-edit <sha>` on v2.3/next, push, PR comment, board rows of the
#         reverted commit's IDs -> blocked, Notes `reverted <sha7>: <reason>`. Never
#         force-pushes.
# batch   vibe/v2.3/batches/<date>-<14|19>-<repo>.md for origin/<base>..origin/v2.3/next
#         (base: android, myitmoapi master; web main, dev after WB-06; backend dev): PRs
#         with item IDs, CI links, diffstat, Roborazzi lines, B migration files, the A
#         githubDebug APK in ~/proj/.wt/run/apk/, open risks; ends with the exact promote
#         command for the owner's "OK <repo> <sha>".
# ready   flips board rows `todo` -> `ready` when every `- needs:` entry of the card
#         (lanes/*.md) is a `merged` card, an `open` gate or owner row, or a recipe whose
#         `- produces:` card is merged; never touches other states; prints unknown IDs
#         (exit 1 when there are any).
#
# Tracked as scripts/integrate.sh (L01 G-13b). ~/proj/.wt/bin/integrate fetches origin
# and runs the copy on origin/v2.3/next. Paths derive from ITMO_WT (default
# ~/proj/.wt; its parent holds the main checkouts), never from $0: guards-test points
# ITMO_WT at its replica. Log: ~/proj/.wt/run/integrate.log.

set -u
PATH="$PATH:/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin"

me=integrate
die() { printf '%s: %s\n' "$me" "$*" >&2; exit 2; }
note() { printf '%s: %s\n' "$me" "$*" >&2; }

WT=$(cd "${ITMO_WT:-$HOME/proj/.wt}" 2>/dev/null && pwd -P) || die "no lane root ${ITMO_WT:-$HOME/proj/.wt}"
PROJ=$(dirname "$WT")
RUN="$WT/run"
VIBE="$PROJ/ITMO.Widgets/vibe/v2.3"
BOARD="$VIBE/board.md"
LANES_DIR="$VIBE/lanes"
BATCHES="$VIBE/batches"
LOG="$RUN/integrate.log"
SIZE_LIMIT=1500
QUEUE_STOP=10
TAB=$(printf '\t')

command -v jq > /dev/null 2>&1 || die "jq is required"

pr_json=""
board=$BOARD

# ---- repositories ------------------------------------------------------------------

repo_info() { # repo -> sets slug letter default main
  case $1 in
