  list) cmd_list ${rest[@]+"${rest[@]}"} ;;
  merge) cmd_merge ${rest[@]+"${rest[@]}"} ;;
  revert) cmd_revert ${rest[@]+"${rest[@]}"} ;;
  batch) cmd_batch ${rest[@]+"${rest[@]}"} ;;
  ready) cmd_ready ${rest[@]+"${rest[@]}"} ;;
  -h | --help | help) awk 'NR > 1 && !/^#/ { exit } NR > 1' "$0" ;;
  *) die "unknown command '$cmd' (list, merge, revert, batch, ready)" ;;
esac
