args=()
while [ $# -gt 0 ]; do
  case $1 in
    --pr-json) [ $# -ge 2 ] || die "--pr-json needs a file"; pr_json=$2; [ -f "$pr_json" ] || die "$pr_json does not exist"; shift 2 ;;
    --board) [ $# -ge 2 ] || die "--board needs a file"; board=$2; shift 2 ;;
    *) args+=("$1"); shift ;;
  esac
done
[ ${#args[@]} -ge 1 ] || die "usage: integrate list|merge|revert|batch|ready ... (integrate --help)"
cmd=${args[0]}
rest=("${args[@]:1}")
