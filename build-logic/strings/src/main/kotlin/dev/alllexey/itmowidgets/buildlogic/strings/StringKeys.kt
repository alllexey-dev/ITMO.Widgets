package dev.alllexey.itmowidgets.buildlogic.strings

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * The key objects of one module's catalog: `<Area>Strings` and `<Area>Plurals` with a `const val` per `<string>` and
 * `<plurals>`, so code without Compose names a key for `UiText.Res`/`UiText.Plural` the way `Res.string.<key>` names
 * the CMP resource, and a typo fails the build.
 */
object StringKeys {

    const val FILE_NAME = "StringKeys.kt"

    /** `core` -> `Core`, `feature-settings` -> `Settings`. */
    fun area(moduleName: String): String =
        moduleName.removePrefix("feature-").split('-').joinToString("") { it.replaceFirstChar(Char::uppercaseChar) }

    fun render(packageName: String, area: String, keys: AndroidStringIds.Keys): String = buildString {
        appendLine("// Generated by itmowidgets.strings from this module's composeResources/values; do not edit.")
        appendLine("package $packageName")
        appendKeys("${area}Strings", "`<string>`", "UiText.Res", keys.strings)
        appendKeys("${area}Plurals", "`<plurals>`", "UiText.Plural", keys.plurals)
    }

    private fun StringBuilder.appendKeys(name: String, kind: String, uiText: String, keys: List<String>) {
        appendLine()
        appendLine("/** The $kind keys of this module's catalog, for `$uiText` (ADR 0028). */")
        appendLine("public object $name {")
        keys.forEach { appendLine("    public const val $it: String = \"$it\"") }
        appendLine("}")
    }
}

/** Writes [StringKeys] of one module from its `composeResources`. */
abstract class GenerateStringKeys : DefaultTask() {

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val resourcesDir: DirectoryProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val area: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        val target = File(out, packageName.get().replace('.', '/') + "/${StringKeys.FILE_NAME}")
        target.parentFile.mkdirs()
        val keys = AndroidStringIds.keys(resourcesDir.get().asFile)
        target.writeText(StringKeys.render(packageName.get(), area.get(), keys))
    }
}
